"""The as-built summary docs/design_summary.md (needs pcbnew).

    "C:\\Program Files\\KiCad\\9.0\\bin\\python.exe" tools\\report_design.py
Read-only on the board; safe while KiCad is open.
"""
from __future__ import annotations

import json
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import params as P  # noqa: E402

ROOT = os.path.dirname(HERE)


def engagement():
    tip = P.STACK["post_tip_y"]
    lo, hi = (round(f - tip, 3) for f in P.J6_FACE_Y)
    return {"tip_y": tip, "min": lo, "max": hi, "limits": list(P.ENGAGEMENT_LIMITS),
            "ok": P.ENGAGEMENT_LIMITS[0] <= lo and hi <= P.ENGAGEMENT_LIMITS[1]}


def main():
    import pcbnew
    mm = pcbnew.ToMM
    b = pcbnew.LoadBoard(os.path.join(ROOT, P.PROJECT + ".kicad_pcb"))
    out = ["# As-built design summary (generated by tools/report_design.py; do not edit)", "",
           f"Project {P.PROJECT} rev {P.REVISION}, {P.DATE}. Frames: KiCad K (x_K = X + 100, y_K = Z + 100) and "
           "enclosure E (X, Z; Y up the device). All SMD parts and the jack are on F.Cu (faces +Y, the top); the THT "
           "headers are footprints on B.Cu (bodies under the board).", ""]
    bb = b.GetBoardEdgesBoundingBox()
    ds = b.GetDesignSettings()
    out.append(f"Board outline bbox (K): x {mm(bb.GetLeft()):.3f}..{mm(bb.GetRight()):.3f}, "
               f"y {mm(bb.GetTop()):.3f}..{mm(bb.GetBottom()):.3f}; thickness {mm(ds.GetBoardThickness()):.3f} mm; "
               f"{b.GetCopperLayerCount()} copper layers.")
    eg = engagement()
    out += ["", "## Parts and sourcing", "",
            *[f"- {r} {h['manufacturer']} {h['mpn']} (LCSC {h['lcsc']}, {P.HDR_JLC_TYPE}; stock {h['stock']} on 2026-11-09), "
              f"pads J6 {'/'.join(h['pads'])}: **hand-soldered by the builder**, in bom.csv, not in jlc_bom.csv / jlc_cpl.csv."
              for r, h in P.HEADERS.items()],
            f"- Header numbers: body {P.HDR['body_h']} / post {P.HDR['post']} / tail {P.HDR['tail']} / pin {P.HDR['post_sq']} sq. "
            f"Source: {P.HDR['source']}.",
            f"- Post tips at Y {P.STACK['post_tip_y']:.2f} (underside {P.STACK['underside_y']:.2f} - body {P.HDR['body_h']} - "
            f"post {P.HDR['post']}); J6 face Y {P.J6_FACE_Y[0]}..{P.J6_FACE_Y[1]} -> engagement {eg['min']:.2f}..{eg['max']:.2f} mm "
            f"(limits {P.ENGAGEMENT_LIMITS[0]}..{P.ENGAGEMENT_LIMITS[1]}). Tails end at Y {P.STACK['tail_tip_y']:.2f} "
            f"({P.STACK['tail_tip_y'] - P.STACK['top_y']:.2f} above the PCB top).",
            f"- Jack {P.JACK['manufacturer']} {P.JACK['mpn']} (LCSC {P.JACK['lcsc']}, stock {P.JACK['stock']}): origin E "
            f"({P.JACK['X']}, {P.JACK['Z']}), nose tip x {P.JACK['nose_tip_x']}, body y {P.STACK['top_y']}..{P.STACK['top_y'] + P.JACK['height']}, "
            f"barrel axis {P.JACK['axis_h']} above the board top; pad 1 sleeve GND, 2 ring HP_R, 3 tip HP_L.",
            "- ICs (LCSC stock 2026-11-09): " + ", ".join(f"{r} {c['mpn']} {c['lcsc']} ({c['stock']})" for r, c in P.ICS.items()) + ".",
            "- CPL rotation offsets (EasyEDA footprints, docs/sources/ee_*.json, tools/cpl_offsets.py): SOT-23-5 +180, TSSOP-20/-14 "
            "+270, SOT-23 +180, 0603 +0, jack +0."]
    out += ["", "## Deviations / notes", ""] + ["- " + d for d in P.DEVIATIONS]
    out += ["", "## Footprints", "", "| Ref | Value | Footprint | x_K | y_K | rot | layer | X (E) | Z (E) | pads (num: net) |",
            "|---|---|---|---|---|---|---|---|---|---|"]

    def key(fp):
        r = fp.GetReference()
        return (r.rstrip("0123456789"), int("".join(c for c in r if c.isdigit()) or 0))
    for fp in sorted(b.GetFootprints(), key=key):
        pos = fp.GetPosition()
        X, Z = P.to_e(mm(pos.x), mm(pos.y))
        pads = ", ".join(f"{p.GetNumber() or 'npth'}: {p.GetNetname() or '-'}" for p in fp.Pads())
        out.append(f"| {fp.GetReference()} | {fp.GetValue()} | {fp.GetFPIDAsString().split(':')[-1]} | {mm(pos.x):.3f} | "
                   f"{mm(pos.y):.3f} | {fp.GetOrientationDegrees():.0f} | {b.GetLayerName(fp.GetLayer())} | {X:.3f} | {Z:.3f} | {pads} |")
    out += ["", "## Copper by net", "", "| Net | F.Cu mm | B.Cu mm | vias |", "|---|---|---|---|"]
    per = defaultdict(lambda: {"len": defaultdict(float), "vias": 0})
    for t in b.GetTracks():
        n = t.GetNetname()
        if t.GetClass() == "PCB_VIA":
            per[n]["vias"] += 1
        else:
            per[n]["len"][b.GetLayerName(t.GetLayer())] += mm(t.GetLength())
    for n in sorted(per):
        d = per[n]
        out.append(f"| {n} | {d['len'].get('F.Cu', 0):.1f} | {d['len'].get('B.Cu', 0):.1f} | {d['vias']} |")
    gate = os.path.join(ROOT, "build", "gate_handedness.json")
    if os.path.exists(gate):
        g = json.load(open(gate, encoding="utf-8"))
        out += ["", "## Handedness / placement gate (tools/check_handedness.py)", ""]
        out += ["- " + line for line in g.get("lines", [])]
    path = os.path.join(ROOT, "docs", "design_summary.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(path)


if __name__ == "__main__":
    main()
