class Builder:
    def __init__(self, board, padnet):
        self.b = board
        self.padnet = padnet
        self.nets = {}
        self.fps = {}

    def net(self, name):
        if name is None:
            return None
        if name not in self.nets:
            ni = pcbnew.NETINFO_ITEM(self.b, name)
            self.b.Add(ni)
            self.nets[name] = ni
        return self.nets[name]

    def pad_xy(self, ref, num):
        for p in self.fps[ref].Pads():
            if p.GetNumber() == num:
                pos = p.GetPosition()
                return (pcbnew.ToMM(pos.x), pcbnew.ToMM(pos.y))
        raise KeyError((ref, num))

    def track(self, net, layer, a, b, width):
        t = pcbnew.PCB_TRACK(self.b)
        t.SetStart(V(*a))
        t.SetEnd(V(*b))
        t.SetWidth(MM(width))
        t.SetLayer(layer)
        t.SetNet(self.net(net))
        self.b.Add(t)

    def via(self, net, at, d=None, drill=None):
        v = pcbnew.PCB_VIA(self.b)
        v.SetPosition(V(*at))
        v.SetViaType(pcbnew.VIATYPE_THROUGH)
        v.SetLayerPair(FC, BC)
        v.SetDrill(MM(drill or P.RULES["via_drill"]))
        try:
            v.SetWidth(MM(d or P.RULES["via_pad"]))
        except TypeError:
            v.SetWidth(FC, MM(d or P.RULES["via_pad"]))
        v.SetNet(self.net(net))
        self.b.Add(v)

    def shape_prims(self, prims, layer, width):
        for p in prims:
            s = pcbnew.PCB_SHAPE(self.b)
            if p[0] == "line":
                s.SetShape(pcbnew.SHAPE_T_SEGMENT)
                s.SetStart(V(*p[1]))
                s.SetEnd(V(*p[2]))
            else:
                s.SetShape(pcbnew.SHAPE_T_ARC)
                s.SetArcGeometry(V(*p[1]), V(*p[2]), V(*p[3]))
            s.SetLayer(layer)
            s.SetWidth(MM(width))
            self.b.Add(s)

    def line(self, a, b, layer, width=0.1):
        self.shape_prims([("line", a, b)], layer, width)

    def circle(self, c, r, layer, width=0.1):
        s = pcbnew.PCB_SHAPE(self.b)
        s.SetShape(pcbnew.SHAPE_T_CIRCLE)
        s.SetCenter(V(*c))
        s.SetEnd(V(c[0] + r, c[1]))
        s.SetLayer(layer)
        s.SetWidth(MM(width))
        self.b.Add(s)

    def text(self, s, at, layer, h=1.0, angle=0, w=None, justify=None, mirror=False):
        t = pcbnew.PCB_TEXT(self.b)
        t.SetText(s)
        t.SetPosition(V(*at))
        t.SetLayer(layer)
        t.SetTextSize(pcbnew.VECTOR2I(MM(h), MM(h)))
        t.SetTextThickness(MM(w if w is not None else max(0.15, h * 0.15)))
        t.SetTextAngleDegrees(angle)
        if justify == "left":
            t.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_LEFT)
        if mirror:
            t.SetMirrored(True)
        self.b.Add(t)
        return t

    def place(self, ref, fpname, at, rot, comp=None, value=None, sym=True, flip=False):
        fp = pcbnew.FootprintLoad(G.PRETTY, fpname)
        if fp is None:
            raise RuntimeError("footprint not found: " + fpname)
        fp.SetReference(ref)
        fp.SetValue(value or fpname)
        fp.SetFPIDAsString(f"{G.LIBNAME}:{fpname}")
        fp.SetPosition(V(*at))
        self.b.Add(fp)
        if flip:
            try:
                fp.Flip(V(*at), pcbnew.FLIP_DIRECTION_LEFT_RIGHT)
            except (AttributeError, TypeError):
                fp.Flip(V(*at), True)
        fp.SetOrientationDegrees(rot)
        if sym:
            fp.SetPath(pcbnew.KIID_PATH("/" + uid("sym", ref)))
            fp.SetSheetname("/")
            fp.SetSheetfile(G.NAME + ".kicad_sch")
        for k, v in sorted((comp or {}).get("fields", {}).items()):
            if k in ("Footprint", "Reference", "Value"):
                continue
            fp.SetField(k, v)
        if comp is not None:
            fp.SetDNP(bool(comp.get("dnp")))
        for fld in fp.GetFields():
            if fld.GetName() != "Reference":
                fld.SetVisible(False)
        fp.Reference().SetVisible(False)
        for pad in fp.Pads():
            nm = self.padnet.get((ref, pad.GetNumber()))
            if nm:
                pad.SetNet(self.net(nm))
        self.fps[ref] = fp
        return fp


def outline_prims():
    o = P.OUTLINE
    k = P.to_k
    pts = [k(o["x0"], o["z1"]), k(o["x1"], o["z1"]), k(o["x1"], o["z0"]), k(o["x0"], o["z0"])]
    return rounded_path(pts, [o["r"]] * 4, closed=True)


def uuid_rewrite(path):
    txt = open(path, encoding="utf-8").read()
    cnt = [0]

    def rep(m):
        cnt[0] += 1
        return f'(uuid "{uid("pcb", cnt[0])}")'
    txt = re.sub(r'\(uuid "[0-9a-fA-F-]{36}"\)', rep, txt)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(txt)
    return cnt[0]


def fp_kind_name(ref):
    if ref in P.ICS:
        return G.STOCK_NAMES[P.ICS[ref]["fp"]]
    if ref == "J4":
        return G.FP_JACK
    if ref in P.HEADERS:
        return G.FP_HDR[ref]
    return G.FP_R if ref.startswith("R") else G.FP_C


def part_pos(ref):
    if ref == "J4":
        j = P.JACK
        return j["X"], j["Z"], j["rot"]
    if ref in P.HEADERS:
        return P.header_centre(ref) + (0,)
    return P.PLACE[ref]


def router_spec(board):
    mm = pcbnew.ToMM
    pads, holes = [], []
    for fp in board.GetFootprints():
        ref = fp.GetReference()
        for pad in fp.Pads():
            pos = pad.GetPosition()
            if pad.GetAttribute() == pcbnew.PAD_ATTRIB_NPTH:
                holes.append({"x": mm(pos.x), "y": mm(pos.y), "r": mm(pad.GetDrillSize().x) / 2, "keep": 0.5})
                continue
            bb = pad.GetBoundingBox()
            smd = pad.GetAttribute() == pcbnew.PAD_ATTRIB_SMD
            circ = pad.GetShape(FC) == pcbnew.PAD_SHAPE_CIRCLE
            pads.append({"ref": ref, "num": pad.GetNumber(), "net": pad.GetNetname(), "x": mm(pos.x), "y": mm(pos.y),
                         "shape": "circle" if circ else "rect", "w": mm(bb.GetWidth()), "h": mm(bb.GetHeight()),
                         "layers": ["F"] if smd else ["F", "B"]})
    o = P.OUTLINE
    x0, z0 = P.to_k(o["x0"], o["z0"])
    x1, z1 = P.to_k(o["x1"], o["z1"])
    vb = [{"x": P.to_k(*P.J6["pins"][k])[0], "y": P.to_k(*P.J6["pins"][k])[1], "r": 0.0, "rv": P.FORBID_R}
          for k in P.FORBIDDEN]
    gnd = [n for n in {p["net"] for p in pads} if n.lstrip("/") == "GND"][0]
    full = {n.lstrip("/"): n for n in {p["net"] for p in pads if p["net"]}}
    return {"grid": P.ROUTE["grid"], "clearance": P.RULES["clearance"], "track": P.ROUTE["track"],
            "via_d": P.RULES["via_pad"], "via_drill": P.RULES["via_drill"], "edge_clear": P.RULES["edge_clearance"],
            "bbox": [x0 - 0.5, z0 - 0.5, x1 + 0.5, z1 + 0.5],
            "outline": {"x0": x0, "y0": z0, "x1": x1, "y1": z1, "r": o["r"]}, "holes": holes, "via_block": vb,
            "pads": pads, "gnd": gnd, "order": [full[n] for n in ROUTE_ORDER if n in full],
            "skip_gnd_refs": list(P.HEADERS), "pour_gnd": ["U2.3"]}


def add_zone(B, board, layer, netname):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    z.SetNet(B.net(netname))
    ol = z.Outline()
    ol.NewOutline()
    poly = prims_to_polygon(outline_prims(), 12)
    for x, y in poly:
        ol.Append(V(x, y))
    z.SetMinThickness(MM(0.20))
    z.SetLocalClearance(MM(P.ROUTE["zone_clearance"]))
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_FULL)
    z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
    z.SetZoneName("GND_" + ("F" if layer == FC else "B"))
    board.Add(z)
    return z


def build(padnet, comps):
    pcbnew.KIID.SeedGenerator(20261109)
    tmp = G.PCB + ".tmp.kicad_pcb"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(skeleton_text())
    board = pcbnew.LoadBoard(tmp)
    B = Builder(board, padnet)
    for nm in sorted(set(padnet.values())):
        B.net(nm)

    B.shape_prims(outline_prims(), pcbnew.Edge_Cuts, 0.05)
    for i, (name, d, X, Z, purpose) in enumerate(P.HOLES):
        fp = B.place(f"H{i + 1}", G.FP_NPTH[d], P.to_k(X, Z), 0, sym=False, value=f"{name} {purpose}")
        fp.SetBoardOnly(True)
    for ref in G.all_refs():
        X, Z, rot = part_pos(ref)
        B.place(ref, fp_kind_name(ref), P.to_k(X, Z), rot, comps[ref], comps[ref]["value"], flip=ref in P.HEADERS)

    # ------------------------------------------------------------ routing (stage A -> router -> stage B)
    spec = router_spec(board)
    os.makedirs(os.path.join(G.ROOT, "build"), exist_ok=True)
    pin = os.path.join(G.ROOT, "build", "pads.json")
    pout = os.path.join(G.ROOT, "build", "routes.json")
    spec_text = json.dumps(spec, indent=1)
    cached = os.path.exists(pin) and os.path.exists(pout) and open(pin).read() == spec_text and         os.path.getmtime(pout) >= os.path.getmtime(pin) and "--reroute" not in sys.argv
    if cached:
        print("router: reusing build/routes.json (identical pads.json)")
    else:
        with open(pin, "w") as fh:
            fh.write(spec_text)
        r = subprocess.run([sys.executable, os.path.join(G.HERE, "router.py"), pin, pout], capture_output=True, text=True)
        print(r.stdout[-3000:])
        if r.returncode != 0:
            print(r.stderr[-3000:])
            raise SystemExit("router failed")
    res = json.load(open(pout))
    for t in res["tracks"]:
        layer = FC if t["layer"] == "F" else BC
        for a, b in zip(t["pts"][:-1], t["pts"][1:]):
            B.track(t["net"], layer, a, b, P.ROUTE["track"])
    for v in res["vias"]:
        B.via(v["net"], (v["x"], v["y"]), v.get("d"), v.get("drill"))
    if res["failed"]:
        print("ROUTING FAILURES:", len(res["failed"]))

    # ------------------------------------------------------------ pours
    gnd = spec["gnd"]
    zones = [add_zone(B, board, FC, gnd), add_zone(B, board, BC, gnd)]

    # ------------------------------------------------------------ documentation layer: J6 reference circles
    U3 = pcbnew.User_3
    for pin_, (X, Z) in P.J6["pins"].items():
        B.circle(P.to_k(X, Z), 0.5, U3, 0.05)
        B.text(f"J6-{pin_}", P.to_k(X, Z - 1.1), U3, 0.35)
        if pin_ in P.FORBIDDEN:
            B.circle(P.to_k(X, Z), P.FORBID_R, U3, 0.05)

    # ------------------------------------------------------------ silkscreen (top)
    SF = pcbnew.F_SilkS
    for s_, (X, Z, h) in SILK_TEXT.items():
        B.text(s_.split("|")[0], P.to_k(X, Z), SF, h)
    B.text(f"SILKSCREEN AUDIO ATTACHMENT rev {P.REVISION}", P.to_k(29.5, 3.2), pcbnew.B_SilkS, 1.0, mirror=True)
    notes = [
        f"SILKSCREEN AUDIO ATTACHMENT rev {P.REVISION} - FAB NOTES (JLCPCB standard 2-layer)",
        "FR-4 1.0 mm, 1 oz, any solder mask colour (black preferred), white silk, LF-HASL or ENIG. No order numbers.",
        "All SMD parts on the top side (F.Cu). J1 (1x4), J2 and J3 (1x1) THT headers are NOT assembled: hand-soldered from the underside.",
        "Header pads are named by the mating J6 pin: J1 1 GND, 2 BCLK, 3 DOUT, 4 GND; J2 9 WS; J3 12 VBAT. No pad or hole at J6 5-8, 10, 11.",
        "4 NPTH: 2 x 4.80 lid screw columns, 2 x 1.30 jack pegs. GND pours on both layers.",
    ]
    for i, s_ in enumerate(notes):
        B.text(s_, (96.0, 110.0 + i * 1.6), pcbnew.Cmts_User, 0.9, 0, justify="left")

    # ------------------------------------------------------------ fill, save
    board.BuildConnectivity()
    filler = pcbnew.ZONE_FILLER(board)
    filler.Fill(board.Zones())
    board.SetFileName(G.PCB)
    pcbnew.SaveBoard(G.PCB, board, True)
    os.remove(tmp)
    for extra in (tmp.replace(".kicad_pcb", ".kicad_pro"), tmp.replace(".kicad_pcb", ".kicad_prl")):
        if os.path.exists(extra):
            os.remove(extra)
    n = uuid_rewrite(G.PCB)
    b2 = pcbnew.LoadBoard(G.PCB)
    b2.BuildConnectivity()
    pcbnew.ZONE_FILLER(b2).Fill(b2.Zones())
    pcbnew.SaveBoard(G.PCB, b2, True)
    print("board saved; uuids:", n, "routing failures:", len(res["failed"]))
    return res


